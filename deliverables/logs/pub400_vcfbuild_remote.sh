#!/QOpenSys/usr/bin/sh
SRCLIB=ASHIBATA1; OBJLIB=ASHIBATA2
run() { echo "$ $1"; system -v "$1" 2>&1 | grep -E 'CPF|CPD|CPC|RNS|RNF|CPI|DDS|\*' | grep -vE '^\s*$' ; }
run "ADDLIBLE LIB($OBJLIB)"
run "CHGLIBL LIBL($OBJLIB $SRCLIB QGPL QTEMP) CURLIB($OBJLIB)"
# --- physical files (create only if missing; keep existing data) ---
for f in AWARDDB BMOVDB EXHBDB GUESTBKDB LRN400STR SECOFRS SETTINGS VOTINGDB; do
  system "CHKOBJ OBJ($OBJLIB/$f) OBJTYPE(*FILE)" >/dev/null 2>&1 && echo "keep PF $f (exists, data retained)" \
    || run "CRTPF FILE($OBJLIB/$f) SRCFILE($SRCLIB/QDDSSRC) SRCMBR($f) SIZE(*NOMAX)"
done
# --- display files ---
for f in ADMSCR ADMVOTERES BMOVSCR CREDITSSCR EXHBMENUSC GUESTBKSCR INTERSCR LRN400SCR LRNAUTO PASSSCR SETUPSCR TESTSUITE VOTESCR; do
  system "DLTF FILE($OBJLIB/$f)" >/dev/null 2>&1
  if [ "$f" = LRNAUTO ]; then run "CRTDSPF FILE($OBJLIB/$f) SRCFILE($SRCLIB/QSDASRC) SRCMBR($f) WAITRCD(10)"; else run "CRTDSPF FILE($OBJLIB/$f) SRCFILE($SRCLIB/QSDASRC) SRCMBR($f)"; fi
done
# --- printer files ---
for f in CMTPRTF CMTTST TESTPRT2 VOTEPRTF; do
  system "DLTF FILE($OBJLIB/$f)" >/dev/null 2>&1
  run "CRTPRTF FILE($OBJLIB/$f) SRCFILE($SRCLIB/QRLUSRC) SRCMBR($f)"
done
# --- menus (DSPF + MSGF with USRnnnn command messages) ---
for m in VCFMAIN MAIN ADMMAIN; do
  system "DLTMNU MENU($OBJLIB/$m)" >/dev/null 2>&1
  system "DLTF FILE($OBJLIB/$m)" >/dev/null 2>&1
  system "DLTMSGF MSGF($OBJLIB/${m}QQ)" >/dev/null 2>&1
  run "CRTDSPF FILE($OBJLIB/$m) SRCFILE($SRCLIB/QMNUSRC) SRCMBR($m)"
  run "CRTMSGF MSGF($OBJLIB/${m}QQ)"
  run "CRTMNU MENU($OBJLIB/$m) TYPE(*DSPF) DSPF($OBJLIB/$m) MSGF($OBJLIB/${m}QQ) CMDLIN(*LONG)"
done
run "ADDMSGD MSGID(USR0001) MSGF($OBJLIB/MAINQQ) MSG('GO VCFEXPO/NAV001')"
run "ADDMSGD MSGID(USR0002) MSGF($OBJLIB/MAINQQ) MSG('GO VCFEXPO/HISTMNU')"
run "ADDMSGD MSGID(USR0003) MSGF($OBJLIB/MAINQQ) MSG('GO VCFEXPO/ABOUT150')"
run "ADDMSGD MSGID(USR0004) MSGF($OBJLIB/MAINQQ) MSG('GO VCFEXPO/ABTGRTIE')"
run "ADDMSGD MSGID(USR0080) MSGF($OBJLIB/MAINQQ) MSG('signoff')"
run "ADDMSGD MSGID(USR0001) MSGF($OBJLIB/VCFMAINQQ) MSG('call ASHIBATA2/lrn400')"
run "ADDMSGD MSGID(USR0011) MSGF($OBJLIB/VCFMAINQQ) MSG('CALL ASHIBATA2/VOTESTUB')"
run "ADDMSGD MSGID(USR0012) MSGF($OBJLIB/VCFMAINQQ) MSG('CALL ASHIBATA2/ADDGBSTUB')"
run "ADDMSGD MSGID(USR0013) MSGF($OBJLIB/VCFMAINQQ) MSG('CALL ASHIBATA2/READGBSTUB')"
run "ADDMSGD MSGID(USR0080) MSGF($OBJLIB/VCFMAINQQ) MSG('signoff')"
# --- RPG IV programs (bound, default activation group as in the original CRTBNDRPG) ---
for p in NTRSTIT PARAMETER PRTLSTVOTE PRTLSTCMT PRINTER CREDITS BEEMOVIE ADDVOTE ADDGBCMT READGBCMT LRN400 LRN400AUT EXHBMENU ADMADDSOFR ADMCRTEXHB ADMHIDECMT ADMLRN400 ADMOFRLIST ADMSETTING ADMVOTERPT; do
  system "DLTPGM PGM($OBJLIB/$p)" >/dev/null 2>&1
  run "CRTBNDRPG PGM($OBJLIB/$p) SRCFILE($SRCLIB/QRPGLESRC) SRCMBR($p) DBGVIEW(*SOURCE) OPTION(*NOSRCSTMT)"
done
# --- CL launcher stubs ---
for p in VOTESTUB ADDGBSTUB READGBSTUB VCFSTUB LRN400STUB; do
  system "DLTPGM PGM($OBJLIB/$p)" >/dev/null 2>&1
  run "CRTCLPGM PGM($OBJLIB/$p) SRCFILE($SRCLIB/QCLSRC) SRCMBR($p)"
done
# --- commands ---
system "DLTCMD CMD($OBJLIB/STREXHB)" >/dev/null 2>&1;    run "CRTCMD CMD($OBJLIB/STREXHB) PGM($OBJLIB/VCFSTUB) SRCFILE($SRCLIB/QCMDSRC) SRCMBR(STREXHB)"
system "DLTCMD CMD($OBJLIB/STREXHBEDT)" >/dev/null 2>&1; run "CRTCMD CMD($OBJLIB/STREXHBEDT) PGM($OBJLIB/ADMCRTEXHB) SRCFILE($SRCLIB/QCMDSRC) SRCMBR(STREXHBEDT)"
system "DLTCMD CMD($OBJLIB/STRVOTERPT)" >/dev/null 2>&1; run "CRTCMD CMD($OBJLIB/STRVOTERPT) PGM($OBJLIB/ADMVOTERPT) SRCFILE($SRCLIB/QCMDSRC) SRCMBR(STRVOTERPT)"
system "DLTCMD CMD($OBJLIB/STRCMTEDT)" >/dev/null 2>&1;  run "CRTCMD CMD($OBJLIB/STRCMTEDT) PGM($OBJLIB/ADMHIDECMT) SRCFILE($SRCLIB/QCMDSRC) SRCMBR(STRCMTEDT)"
echo "=== object inventory $OBJLIB"
system "DSPOBJD OBJ($OBJLIB/*ALL) OBJTYPE(*ALL) DETAIL(*BASIC)" | grep -E '^ *[A-Z0-9]+ +\*'
